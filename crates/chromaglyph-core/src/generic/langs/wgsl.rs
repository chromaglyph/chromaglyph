//! Built-in WGSL spec: the WebGPU Shading Language. Five keyword groups
//! (control, declarations, constants, type words, builtin functions),
//! `"` strings, `//` and `/* */` comments, numbers with WGSL suffixes
//! (`42u`, `1.5f`, `0.5h` ride the ordinary number state — suffix
//! letters are identifier chars). Attribute names (`@vertex`,
//! `@builtin(position)`) are contextual keywords: the `@` is a plain
//! boundary and the word after it stays uncolored, like the C# spec's
//! contextual words.

