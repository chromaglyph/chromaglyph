pub fn spec() -> LanguageSpec {
    LanguageSpec {
        name: "wgsl",
        keywords: &[
            KeywordGroup {
                scope: "keyword.control.wgsl",
                followed_by: None,
                value: false,
                words: &[
                    "break",
                    "case",
                    "continue",
                    "continuing",
                    "default",
                    "discard",
                    "else",
                    "for",
                    "if",
                    "loop",
                    "return",
                    "switch",
                    "while",
                ],
            },
            KeywordGroup {
                scope: "storage.type.wgsl",
                followed_by: None,
                value: false,
                words: &[
                    "alias",
                    "const",
                    "const_assert",
                    "diagnostic",
                    "enable",
                    "fn",
                    "let",
                    "override",
                    "requires",
                    "struct",
                    "var",
                ],
            },
            KeywordGroup {
                scope: "constant.language.wgsl",
                followed_by: None,
                value: false,
                words: &["true", "false"],
            },
            KeywordGroup {
                scope: "support.type.wgsl",
                followed_by: None,
                value: false,
                words: TYPES,
            },
            KeywordGroup {
                scope: "support.function.wgsl",
                followed_by: None,
                value: false,
                words: BUILTINS,
            },
        ],
        strings: &[StringKind {
            quote: '"',
            escapes: true,
            interpolation: None,
            scope: "string.quoted.double.wgsl",
        }],
        spans: &[
            SpanKind {
                open: "//",
                close: "",
                scope: "comment.line.double-slash.wgsl",
            },
            SpanKind {
                open: "/*",
                close: "*/",
                scope: "comment.block.wgsl",
            },
        ],
        tags: &[],
        blocks: &[],
        numbers: true,
        number_scope: "constant.numeric.wgsl",
        ident_extra: &[],
    }
}

/// Curated oracle samples: every state transition order, unterminated
/// states, keyword-boundary soup (plus whatever the spec-derived random
/// assembly in `oracle.rs` adds on top).
pub(in crate::generic) fn samples() -> Vec<String> {
    [
        "let x = 1;",
        "// comment\nfn main() {}",
        "let s = \"fn // let\";",
        "// \"quoted\" comment\nlet y;",
        "\"\"\"",
        "//////",
        "fnfn fn fnx xfn _fn fn_",
        "a\"b\"c\"d",
        "let s = \"\";",
        "let esc = \"quote: \\\" back: \\\\\";",
        "/* block */ let x;",
        "/* multi\nline\ncomment */ let y;",
        "/* unterminated block let fn",
        "struct Uniforms { mvp: mat4x4f, tint: vec4f, count: u32 };",
        "@vertex fn vs(@builtin(vertex_index) vi: u32) -> @builtin(position) vec4f { return vec4f(0.0, 0.0, 0.0, 1.0); }",
        "var<storage, read> particles: array<Particle>;",
        "let n = normalize(vec3f(0.0, 1.0, 0.0));",
        "let d = dot(n, vec3f(1.0, 0.0, 0.0)) + clamp(t, 0.0, 1.0);",
        "let c = textureSample(tex, samp, uv);",
        "atomicAdd(&counter, 1u);",
        "enable f16; requires f16; diagnostic(off, derivative_uniformity);",
        "let a = 42u; let b = 3.14f; let c = 0x1F; let d = 0.5h; let e = 1e-5;",
        "vec2 vec2f vec2h vec2i vec2u vec2x xvec2 1vec2",
        "mat2x2 mat2x2f mat2x2h mat2x2x",
        "atomic atomicAdd atomicStore xatomic",
        "sampler sampler_comparison samplerx",
        "texture_2d texture_2d_array texture_depth_2d texturex",
        "subgroupBroadcast subgroupBroadcastFirst",
        "switch (x) { case 0: { break; } default: { discard; } }",
        "loop { if x > 0 { break; } continuing { discard; } }",
        "fn f() -> f32 { return sin(x) * cos(y) + exp2(z); }",
        "\nfn at_line_start\nlet at_line_start\n42 at_line_start",
    ]
    .iter()
    .map(|s| s.to_string())
    .collect()
}
