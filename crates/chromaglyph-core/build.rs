//! Embeds the vendored theme collection (`themes/tm/`, written by
//! `scripts/vendor-themes.mjs`) into the crate: each theme's JSON is gzipped
//! into `OUT_DIR` and a registry table is generated from `index.json`.
//!
//! Compressing buys a 7x smaller binary (the collection is ~1.9 MB raw,
//! ~250 KB gzipped) while the files in the repository stay byte-for-byte
//! upstream. Inflating a theme on demand costs well under a millisecond.

use std::fmt::Write as _;
use std::fs;
use std::io::Write as _;
use std::path::Path;

fn main() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let out_dir = std::env::var("OUT_DIR").unwrap();
    let themes_dir = Path::new(&manifest_dir).join("themes/tm");
    let gz_dir = Path::new(&out_dir).join("themes");
    fs::create_dir_all(&gz_dir).unwrap();

    // a directory path makes cargo scan it recursively, so a re-vendor
    // (new/removed/changed files) rebuilds the table
    println!("cargo:rerun-if-changed={}", themes_dir.display());

    let index: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(themes_dir.join("index.json")).unwrap()).unwrap();
    let version = index["tm-themes"]
        .as_str()
        .expect("index.json: tm-themes version");
    let themes = index["themes"]
        .as_array()
        .expect("index.json: themes array");

    let mut table = String::new();
    writeln!(
        table,
        "// @generated by build.rs from themes/tm/index.json — do not edit"
    )
    .unwrap();
    writeln!(
        table,
        "pub(crate) const TM_THEMES_VERSION: &str = {version:?};"
    )
    .unwrap();
    writeln!(table, "pub(crate) static BUILTINS: &[BuiltinTheme] = &[").unwrap();
    for theme in themes {
        let field = |key: &str| {
            theme[key]
                .as_str()
                .unwrap_or_else(|| panic!("index.json: theme missing {key}"))
        };
        let slug = field("name");
        let kind = match field("type") {
            "dark" => "ThemeKind::Dark",
            "light" => "ThemeKind::Light",
            other => panic!("index.json: {slug}: unknown type {other:?}"),
        };

        let json = fs::read(themes_dir.join(format!("{slug}.json"))).unwrap();
        let gz_path = gz_dir.join(format!("{slug}.json.gz"));
        let mut encoder = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::best());
        encoder.write_all(&json).unwrap();
        fs::write(&gz_path, encoder.finish().unwrap()).unwrap();

        writeln!(
            table,
            "    BuiltinTheme {{ slug: {slug:?}, display_name: {:?}, kind: {kind}, license: {:?}, license_url: {:?}, source: {:?}, json_gz: include_bytes!({:?}) }},",
            field("displayName"),
            field("license"),
            field("licenseUrl"),
            field("source"),
            gz_path.display().to_string(),
        )
        .unwrap();
    }
    writeln!(table, "];").unwrap();

    fs::write(Path::new(&out_dir).join("builtin_themes.rs"), table).unwrap();
}
